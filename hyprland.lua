-- Hyprland 主配置（Hyprland 0.56+ / Lua 配置）
--
-- 结构参考 ~/.config/sway：
--   sway/config        → hyprland.lua（入口、启动项）
--   sway/options       → conf/appearance.lua
--   sway/noctalia      → conf/theme.lua
--   sway/window_rules  → conf/window_rules.lua
--   sway 的快捷键       → conf/keybinds.lua
--
-- 修改后保存会自动重载；也可以手动执行 hyprctl reload。

hl.config({ autogenerated = false })

-- 启动时执行（对应 sway 顶部的 exec 行）
hl.on("hyprland.start", function()
	hl.exec_cmd("dbus-update-activation-environment --systemd --all")
	hl.exec_cmd("systemctl --user start hyprland-session.target")
	-- hl.exec_cmd("hyprpaper")
	hl.exec_cmd("noctalia")
	hl.exec_cmd("fcitx5 -d")
end)

require("conf.env")        -- 环境变量（原 env_var.conf）
require("conf.monitors")   -- 显示器
require("conf.appearance") -- 外观、模糊、输入、动画
require("conf.keybinds")     -- 快捷键
require("conf.window_rules") -- 窗口规则
require("conf.layer_rules")  -- 图层规则

-- For Noctalia Color templates
require("noctalia").apply_theme()
require("shadow")
